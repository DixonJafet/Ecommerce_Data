USE WAREHOUSE DATA_WH;

-- Create database
CREATE DATABASE ecommerce_db;

-- Create schema
CREATE SCHEMA ecommerce_db.raw_data;
CREATE SCHEMA ecommerce_db.processed;

ALTER SCHEMA ecommerce_db.processed 
RENAME TO ecommerce_db.processed_data;


CREATE STORAGE INTEGRATION s3_integration
    TYPE = EXTERNAL_STAGE
    STORAGE_PROVIDER = 'S3'
    ENABLED = TRUE
    STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::391738927106:role/snowflake-s3-role'
    STORAGE_ALLOWED_LOCATIONS = ('s3://commerce-data-391738927106-us-east-2-an/processed/');


DESC INTEGRATION s3_integration;

DESC INTEGRATION s3_integration;


USE SCHEMA processed_data;

CREATE STAGE s3_processed_stage
    STORAGE_INTEGRATION = s3_integration
    URL = 's3://commerce-data-391738927106-us-east-2-an/processed/'
    FILE_FORMAT = (
        TYPE = 'CSV'
        FIELD_OPTIONALLY_ENCLOSED_BY = '"'
        SKIP_HEADER = 1
        NULL_IF = ('NULL', 'null', '')
    );


LIST @s3_processed_stage;

CREATE CATALOG INTEGRATION glue_catalog_integration
    CATALOG_SOURCE = AWS_GLUE
    CATALOG_NAMESPACE = 'db_kpi'
    TABLE_FORMAT = ICEBERG
    GLUE_AWS_ROLE_ARN = 'arn:aws:iam::391738927106:role/snowflake-glue-role'
    GLUE_CATALOG_ID = '391738927106'
    GLUE_REGION = 'us-east-2'
    ENABLED = TRUE;


USE DATABASE ecommerce_db;
USE SCHEMA processed_data;

CREATE TABLE IF NOT EXISTS CUSTOMERS_DATASET (
    CUSTOMER_ID VARCHAR,
    CUSTOMER_UNIQUE_ID VARCHAR,
    CUSTOMER_ZIP_CODE_PREFIX NUMBER,
    CUSTOMER_CITY VARCHAR,
    CUSTOMER_STATE VARCHAR
);

CREATE TABLE IF NOT EXISTS GEOLOCATION_DATASET (
    GEOLOCATION_ZIP_CODE_PREFIX NUMBER,
    GEOLOCATION_LAT FLOAT,
    GEOLOCATION_LNG FLOAT,
    GEOLOCATION_CITY VARCHAR,
    GEOLOCATION_STATE VARCHAR
);

CREATE TABLE IF NOT EXISTS ORDER_ITEMS_DATASET (
    ORDER_ID VARCHAR,
    ORDER_ITEM_ID NUMBER,
    PRODUCT_ID VARCHAR,
    SELLER_ID VARCHAR,
    SHIPPING_LIMIT_DATE VARCHAR,
    PRICE FLOAT,
    FREIGHT_VALUE FLOAT
);

CREATE TABLE IF NOT EXISTS ORDER_PAYMENTS_DATASET (
    ORDER_ID VARCHAR,
    PAYMENT_SEQUENTIAL NUMBER,
    PAYMENT_TYPE VARCHAR,
    PAYMENT_INSTALLMENTS NUMBER,
    PAYMENT_VALUE FLOAT
);

CREATE TABLE IF NOT EXISTS ORDER_REVIEWS_DATASET (
    REVIEW_ID VARCHAR,
    ORDER_ID VARCHAR,
    REVIEW_SCORE NUMBER,
    REVIEW_COMMENT_TITLE VARCHAR,
    REVIEW_COMMENT_MESSAGE VARCHAR,
    REVIEW_CREATION_DATE VARCHAR,
    REVIEW_ANSWER_TIMESTAMP VARCHAR
);

CREATE TABLE IF NOT EXISTS ORDERS_DATASET (
    ORDER_ID VARCHAR,
    CUSTOMER_ID VARCHAR,
    ORDER_STATUS VARCHAR,
    ORDER_PURCHASE_TIMESTAMP VARCHAR,
    ORDER_APPROVED_AT VARCHAR,
    ORDER_DELIVERED_CARRIER_DATE VARCHAR,
    ORDER_DELIVERED_CUSTOMER_DATE VARCHAR,
    ORDER_ESTIMATED_DELIVERY_DATE VARCHAR
);

CREATE TABLE IF NOT EXISTS PRODUCTS_DATASET (
    PRODUCT_ID VARCHAR,
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_NAME_LENGHT NUMBER,
    PRODUCT_DESCRIPTION_LENGHT NUMBER,
    PRODUCT_PHOTOS_QTY NUMBER,
    PRODUCT_WEIGHT_G NUMBER,
    PRODUCT_LENGTH_CM NUMBER,
    PRODUCT_HEIGHT_CM NUMBER,
    PRODUCT_WIDTH_CM NUMBER
);

CREATE TABLE IF NOT EXISTS SELLERS_DATASET (
    SELLER_ID VARCHAR,
    SELLER_ZIP_CODE_PREFIX NUMBER,
    SELLER_CITY VARCHAR,
    SELLER_STATE VARCHAR
);

CREATE TABLE IF NOT EXISTS PRODUCT_CATEGORY_NAME_TRANSLATION (
    PRODUCT_CATEGORY_NAME VARCHAR,
    PRODUCT_CATEGORY_NAME_ENGLISH VARCHAR
);

USE DATABASE ecommerce_db;
USE SCHEMA processed_data;

