    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    SKIP_HEADER = 1
    NULL_IF = ('NULL', 'null', '')
    EMPTY_FIELD_AS_NULL = TRUE;

USE DATABASE ecommerce_db;
USE SCHEMA processed_data;

CREATE PIPE customers_pipe
    AUTO_INGEST = TRUE
    AS
    COPY INTO customers_dataset
    FROM @s3_processed_stage/customers_dataset.csv
    FILE_FORMAT = (FORMAT_NAME = 'csv_format');